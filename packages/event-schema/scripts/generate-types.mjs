import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { compileFromFile } from 'json-schema-to-typescript';

const packageDirectory = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(packageDirectory, 'schema/security-event-v1.schema.json');
const outputPath = resolve(packageDirectory, 'src/generated/security-event-v1.ts');

const declaration = await compileFromFile(schemaPath, {
  bannerComment: `/**
 * Generated from schema/security-event-v1.schema.json.
 * Do not edit this file directly; run the package generate command.
 */`,
  unknownAny: true,
});

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, declaration, 'utf8');
